export const t = (lang: Lang) => ui[lang];
export type UI = ReturnType<typeof t>;

export const dateLocale = (lang: Lang) => (lang === 'vi' ? 'vi-VN' : 'en-US');

export function formatDate(date: Date, lang: Lang, short = false): string {
  return date.toLocaleDateString(dateLocale(lang), short ? { day: 'numeric', month: 'short' } : { day: 'numeric', month: 'long', year: 'numeric' });
}

// "3 days ago" / "3 ngày trước"
export function timeAgo(date: Date, lang: Lang, now = Date.now()): string {
  const u = t(lang);
  const s = Math.max(0, Math.round((now - date.getTime()) / 1000));
  if (s < 60) return u.justNow;
  const m = Math.floor(s / 60);
  if (m < 60) return u.ago(`${m} ${u.units.m}`);
  const h = Math.floor(m / 60);
  if (h < 24) return u.ago(`${h} ${u.units.h}`);
  const d = Math.floor(h / 24);
  if (d < 7) return u.ago(`${d} ${u.units.d}`);
  if (d < 30) return u.ago(`${Math.floor(d / 7)} ${u.units.w}`);
  if (d < 365) return u.ago(`${Math.floor(d / 30)} ${u.units.mo}`);
  return u.ago(`${Math.floor(d / 365)} ${u.units.y}`);
}

// A plain-text slice of the interface strings, safe to hand to client components
type UIStrings = ReturnType<typeof t>;
type StringKeys = { [K in keyof UIStrings]: UIStrings[K] extends string ? K : never }[keyof UIStrings];
export function strings<K extends StringKeys>(lang: Lang, ...keys: K[]): Record<K, string> {
  const u = t(lang);
  return Object.fromEntries(keys.map((k) => [k, u[k] as string])) as Record<K, string>;
}
