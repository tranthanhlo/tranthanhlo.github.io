// Vietnamese is the default and lives at the site root; English lives under /en/.
export type Lang = 'vi' | 'en';
export const LANGS: Lang[] = ['vi', 'en'];
export const otherLang = (lang: Lang): Lang => (lang === 'vi' ? 'en' : 'vi');
export const isLang = (v: string): v is Lang => v === 'vi' || v === 'en';

// Prefix a path with the language: href('en', '/blog') → '/en/blog', href('vi', '/blog') → '/blog'
export function href(lang: Lang, path = '/'): string {
  if (lang === 'vi') return path;
  return path === '/' ? '/en' : `/en${path}`;
}

// English text when there is one, otherwise the Vietnamese original
export function pick<T extends string | null | undefined>(lang: Lang, vi: string, en: T): string {
  return lang === 'en' && en ? en : vi;
}

// 1234 → "1,2 N" / "1.2K", like the app
function compact(n: number, locale: string): string {
  return new Intl.NumberFormat(locale, { notation: 'compact', maximumFractionDigits: 1 }).format(n);
}

